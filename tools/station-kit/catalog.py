#!/usr/bin/env python3
"""Compile all (system, name) station records already bundled by the game.
No network, no random choices and no changes to the authoritative data files.
"""
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
DATA=ROOT/'RailwayGameApp/Resources/RealRailways'
landmarks={
 ('tra_sched','台北'):'taipei',('tra_sched','台中'):'taichung',('tra_sched','高雄'):'kaohsiung',
 ('tra_sched','新竹'):'hsinchu',('tra_sched','台南'):'tainan',('tra_sched','嘉義'):'chiayi',
 ('tra_sched','基隆'):'keelung',('tra_sched','南港'):'nangang',('tra_sched','板橋'):'banqiao',
 ('tra_sched','花蓮'):'hualien',('tra_sched','台東'):'taitung',('tra_sched','新左營'):'zuoying',
 ('tra_sched','新烏日'):'hsrTaichung',('thsr_sched','台中'):'hsrTaichung',
 ('thsr_sched','桃園'):'hsrTaoyuan',('thsr_sched','新竹'):'hsrHsinchu',('thsr_sched','台南'):'hsrTainan',
 ('thsr_sched','南港'):'nangang',('thsr_sched','板橋'):'banqiao',('thsr_sched','台北'):'taipei',('thsr_sched','左營'):'zuoying',
 ('tra_sched','集集'):'timber',('tra_sched','車埕'):'timber',('tra_sched','菁桐'):'timber',
 ('tra_sched','十分'):'heritage',('tra_sched','平溪'):'heritage',('tra_sched','追分'):'heritage',
 ('tra_sched','日南'):'heritage',('tra_sched','保安'):'heritage',('tra_sched','山佳'):'heritage',
 ('afr_sched','阿里山'):'timber',('afr_sched','奮起湖'):'timber',('afr_sched','北門'):'timber',
 ('krtc','美麗島'):'formosa',('krtc','中央公園'):'centralPark',
}
def norm(name): return name.replace('臺','台')
def fnv(text):
 value=2166136261
 for b in text.encode(): value=((value^b)*16777619)&0xffffffff
 return value

def records():
 grouped={}
 for feature in json.loads((DATA/'track_stations.geojson').read_text())['features']:
  p=feature['properties'];key=(p['sys'],p['name'])
  if key not in grouped: grouped[key]={'system':p['sys'],'name':p['name'],'lines':set(),'point':feature['geometry']['coordinates']}
  grouped[key]['lines'].add(p['lineId'])
 classes={norm(k):v for k,v in json.loads((DATA/'tra_station_class.json').read_text()).items()}
 tiers={'特等':0,'一等':1,'二等':2,'三等':3}
 for key in sorted(grouped):
  r=grouped[key];system,name=r['system'],r['name'];seed=fnv(system+'|'+name)
  tier=tiers.get(classes.get(norm(name)),4) if system=='tra_sched' else 1
  profile=landmarks.get((system,norm(name)))
  if profile is None:
   if system=='tra_sched': profile='regional' if tier<4 else 'halt'
   elif system=='afr_sched': profile='timber'
   elif system=='thsr_sched': profile='highSpeed'
   elif system in ('ntdlrt','ntalrt') or system=='krtc' and any(line=='C' or line.startswith('KL') or '輕軌' in line for line in r['lines']): profile='lightRail'
   elif system in ('tmrt','sanying','tymc') or system=='mrt' and (
    any(line in ('BR','Y','R_XBT') for line in r['lines']) or name in ('淡水','紅樹林','竹圍','關渡','忠義','復興崗','奇岩','唭哩岸','石牌','明德','芝山','士林','劍潭','圓山','小碧潭')): profile='elevated'
   else: profile='underground'
  r.update(id='station-'+system+'-'+format(seed,'08x'),seed=seed,tier=tier,profile=profile,planned=system=='sanying',landmark=(system,norm(name)) in landmarks,lines=sorted(r['lines']))
  yield r

def swift_string(value): return json.dumps(value,ensure_ascii=False)
def generate():
 rows=[]
 for r in records():
  lon,lat=r['point'];lines='['+','.join(map(swift_string,r['lines']))+']'
  rows.append('        Station(id:%s,name:%s,system:%s,latitude:%s,longitude:%s,lines:%s,profile:.%s,tier:%d,seed:%d,planned:%s,isLandmark:%s),'%(swift_string(r['id']),swift_string(r['name']),swift_string(r['system']),lat,lon,lines,r['profile'],r['tier'],r['seed'],str(r['planned']).lower(),str(r['landmark']).lower()))
 return '// Generated by tools/station-kit/catalog.py from the bundled station catalog.\n// Names match the bundled TDX-derived catalog. Coordinates include OSM alignment.\n// Station point data: © OpenStreetMap contributors, ODbL 1.0; building profiles are illustrative art.\n\nextension Map3DStationKit {\n    public static let stations: [Station] = [\n'+'\n'.join(rows)+'\n    ]\n}\n'
if __name__=='__main__':
 import argparse
 parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
 path=ROOT/'Sources/GamePresentation/Map3DStationKitCatalog.swift';content=generate()
 if args.check:
  if path.read_text()!=content: raise SystemExit('Station catalog is stale; run tools/station-kit/catalog.py')
 else: path.write_text(content)
 counts={}
 for r in records(): counts[r['system']]=counts.get(r['system'],0)+1
 print(json.dumps({'stations':sum(counts.values()),'systems':counts},ensure_ascii=False))
