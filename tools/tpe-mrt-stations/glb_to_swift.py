#!/usr/bin/env python3
"""Write the local studio's Tamsui-Xinyi line elevated station GLBs (decision
827) into the game's Swift source as encoded meshes (no third-party modules).

    python3 -I tools/tpe-mrt-stations/glb_to_swift.py \
        --out Sources/GamePresentation/Map3DTaipeiMRTStationMeshes.swift DIR/*.glb

The GLBs are `a91453/railway-assets-private`,
`game-art-previews/docs/art/tpe-mrt-elevated-2026-11/revision-3/`: one
material per palette colour, +x along the track, +y up, +z across, the
ground at y 0 and the rails at y 9.0 (the brief). This tool welds the
vertices at 1 cm, keeps glTF's axes as they are (the station's own: along,
up, across), gives each triangle the index of its material's name in
``MATERIALS`` (``Map3DTaipeiMRTStation.materialColours`` holds the colours
in the same order), and writes each GLB, named by its file name, as base64
of: the vertex count (UInt16), each vertex x, y, z in centimetres (Int16),
the triangle count (UInt16), each triangle's three vertex indices (UInt16)
and material index (UInt8), little-endian.
"""

import argparse
import base64
import json
import os
import struct

MATERIALS = ["roofGold", "trimWhite", "stoneBeige", "lineRed", "eaveTrim", "windowGlass", "pier",
             "graniteGrey", "frameSilver", "roofPale", "roofSeam", "cable", "clampGold"]


def read_glb(path):
    data = open(path, "rb").read()
    if data[:4] != b"glTF":
        raise SystemExit(f"{path}: not a GLB")
    length = struct.unpack_from("<I", data, 12)[0]
    gltf = json.loads(data[20:20 + length])
    offset = 20 + length
    blob_length = struct.unpack_from("<I", data, offset)[0]
    return gltf, data[offset + 8:offset + 8 + blob_length]


def accessor(gltf, blob, index):
    acc = gltf["accessors"][index]
    view = gltf["bufferViews"][acc["bufferView"]]
    start = view.get("byteOffset", 0) + acc.get("byteOffset", 0)
    width = {"SCALAR": 1, "VEC2": 2, "VEC3": 3, "VEC4": 4}[acc["type"]]
    fmt = {5126: "f", 5125: "I", 5123: "H", 5121: "B"}[acc["componentType"]]
    size = struct.calcsize(fmt)
    stride = view.get("byteStride", size * width)
    out = []
    for i in range(acc["count"]):
        values = struct.unpack_from("<" + fmt * width, blob, start + i * stride)
        out.append(values if width > 1 else values[0])
    return out


def encode(path):
    gltf, blob = read_glb(path)
    for node in gltf["nodes"]:
        if any(k in node for k in ("matrix", "translation", "rotation", "scale")):
            raise SystemExit(f"{path}: node {node.get('name')} is transformed; apply it in Blender")
    keys, points, triangles = {}, [], []
    for mesh in gltf["meshes"]:
        for prim in mesh["primitives"]:
            name = gltf["materials"][prim["material"]]["name"]
            if name not in MATERIALS:
                raise SystemExit(f"{path}: material {name} is not in the table")
            paint = MATERIALS.index(name)
            pos = accessor(gltf, blob, prim["attributes"]["POSITION"])
            idx = accessor(gltf, blob, prim["indices"]) if "indices" in prim else list(range(len(pos)))
            local = []
            for (x, y, z) in pos:
                p = (round(x * 100), round(y * 100), round(z * 100))
                if p not in keys:
                    keys[p] = len(points)
                    points.append(p)
                local.append(keys[p])
            for k in range(0, len(idx), 3):
                a, b, c = local[idx[k]], local[idx[k + 1]], local[idx[k + 2]]
                if a != b and b != c and a != c:
                    triangles.append((a, b, c, paint))
    if len(points) > 65535 or len(triangles) > 65535:
        raise SystemExit(f"{path}: too many vertices or triangles")
    out = bytearray(struct.pack("<H", len(points)))
    for p in points:
        if not all(-32768 <= v <= 32767 for v in p):
            raise SystemExit(f"{path}: vertex {p} cm out of range")
        out += struct.pack("<hhh", *p)
    out += struct.pack("<H", len(triangles))
    for a, b, c, paint in triangles:
        out += struct.pack("<HHHB", a, b, c, paint)
    return bytes(out), len(points), len(triangles)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", required=True)
    parser.add_argument("glbs", nargs="+")
    args = parser.parse_args()
    lines = [
        "// Generated by tools/tpe-mrt-stations/glb_to_swift.py from the local studio's",
        "// GLBs (railway-assets-private, game-art-previews/docs/art/tpe-mrt-elevated-2026-11/",
        "// revision-3). Do not edit by hand.",
        "",
        "extension Map3DTaipeiMRTStation {",
        "    /// Each model, by its file name, as `tools/tpe-mrt-stations/glb_to_swift.py` encodes it.",
        "    static let encodedMeshes: [String: String] = [",
    ]
    for path in sorted(args.glbs):
        data, v, t = encode(path)
        name = os.path.splitext(os.path.basename(path))[0]
        print(f"{name}: {v} vertices, {t} triangles, {len(data)} bytes")
        lines.append(f"        // {v} vertices, {t} triangles.")
        lines.append(f'        "{name}": "{base64.b64encode(data).decode()}",')
    lines += ["    ]", "}", ""]
    open(args.out, "w").write("\n".join(lines))


if __name__ == "__main__":
    main()
