def read_glb(path):
    data = open(path, "rb").read()
    if data[:4] != b"glTF":
        raise SystemExit(f"{path}: not a GLB")
    length = struct.unpack_from("<I", data, 12)[0]
    gltf = json.loads(data[20:20 + length])
    offset = 20 + length
    blob_length = struct.unpack_from("<I", data, offset)[0]
    return gltf, data[offset + 8:offset + 8 + blob_length]


def accessor(gltf, blob, index):
    acc = gltf["accessors"][index]
    view = gltf["bufferViews"][acc["bufferView"]]
    start = view.get("byteOffset", 0) + acc.get("byteOffset", 0)
    width = {"SCALAR": 1, "VEC2": 2, "VEC3": 3, "VEC4": 4}[acc["type"]]
    fmt = {5126: "f", 5125: "I", 5123: "H", 5121: "B"}[acc["componentType"]]
    size = struct.calcsize(fmt)
    stride = view.get("byteStride", size * width)
    out = []
    for i in range(acc["count"]):
        values = struct.unpack_from("<" + fmt * width, blob, start + i * stride)
        out.append(values if width > 1 else values[0])
    return out


def rotate(q, v):
    """`v` turned by the unit quaternion `q` (x, y, z, w)."""
    x, y, z, w = q
    vx, vy, vz = v
    # t = 2 q × v; v' = v + w t + q × t
    tx, ty, tz = 2 * (y * vz - z * vy), 2 * (z * vx - x * vz), 2 * (x * vy - y * vx)
    return (vx + w * tx + y * tz - z * ty, vy + w * ty + z * tx - x * tz, vz + w * tz + x * ty - y * tx)


def primitives(path, gltf, nodes):
    """Each primitive with how to place its points: (primitive, translation,
    rotation, scale). Without `nodes`, no node may be transformed (apply it
    in Blender) and the meshes are read in their own order; with it, each
    node's transform is applied, in the nodes' order."""
    if not nodes:
        for node in gltf["nodes"]:
            if any(k in node for k in ("matrix", "translation", "rotation", "scale")):
                raise SystemExit(f"{path}: node {node.get('name')} is transformed; apply it in Blender")
        for mesh in gltf["meshes"]:
            for prim in mesh["primitives"]:
                yield prim, None
        return
    for node in gltf["nodes"]:
        if "mesh" not in node:
            continue
        if "matrix" in node or "children" in node:
            raise SystemExit(f"{path}: node {node.get('name')} has a matrix or children")
        place = (node.get("translation", (0, 0, 0)), node.get("rotation", (0, 0, 0, 1)), node.get("scale", (1, 1, 1)))
        for prim in gltf["meshes"][node["mesh"]]["primitives"]:
            yield prim, place


def encode(path, materials, aliases=None, axes="enu", nodes=False, scale=(1, 1, 1), unsigned_z=True, centre=False, turn=0.0,
           lift=0.0, mid=None, south=None):
    """The GLB at `path` encoded; its vertex and triangle counts, and its
    bounds in metres. With `centre`, `mid` (centimetres east and north) is
    the shift to take off rather than this model's own footprint middle.
    With `south` (metres, the studio's own north before any turn), every
    part that reaches south of it is left out: a part is the triangles of
    one material joined through their welded vertices."""
    aliases = aliases or {}
    gltf, blob = read_glb(path)
    keys, points, triangles, norths = {}, [], [], []
    # `turn`: degrees anticlockwise seen from above, about the GLB's origin.
    turn_cos, turn_sin = math.cos(math.radians(turn)), math.sin(math.radians(turn))
    for prim, place in primitives(path, gltf, nodes):
        if prim.get("mode", 4) != 4:
            raise SystemExit(f"{path}: only triangle lists are read")
        name = gltf["materials"][prim["material"]]["name"]
        name = aliases.get(name, name)
        if name not in materials:
            raise SystemExit(f"{path}: material {name} is not in the material list")
        paint = materials.index(name)
        pos = accessor(gltf, blob, prim["attributes"]["POSITION"])
        idx = accessor(gltf, blob, prim["indices"]) if "indices" in prim else list(range(len(pos)))
        flipped = False
        local = []
        for p in pos:
            x, y, z = p
            if place is not None:
                t, q, s = place
                flipped = s[0] * s[1] * s[2] < 0
                x, y, z = rotate(q, (x * s[0], y * s[1], z * s[2]))
                x, y, z = (x + t[0]) * scale[0], (y + t[1]) * scale[1], (z + t[2]) * scale[2]
            if axes == "enu":
                # glTF (+x east, +y up, +z south) onto (+x east, +y north, +z up).
                east, north = x * turn_cos + z * turn_sin, x * turn_sin - z * turn_cos
                key = (round(east * 100), round(north * 100), round((y + lift) * 100))
            else:
                key = (round(x * 100), round(y * 100), round(z * 100))
            if key not in keys:
                keys[key] = len(points)
                points.append(key)
                norths.append(-z if axes == "enu" else y)
            local.append(keys[key])
        for k in range(0, len(idx), 3):
            a, b, c = local[idx[k]], local[idx[k + 1]], local[idx[k + 2]]
            if flipped:
                b, c = c, b
            if a != b and b != c and a != c:
                triangles.append((a, b, c, paint))
    if south is not None:
        triangles = without_parts_south_of(south, points, norths, triangles)
        used = sorted({i for t in triangles for i in t[:3]})
        index = {old: new for new, old in enumerate(used)}
        points = [points[i] for i in used]
        triangles = [(index[a], index[b], index[c], paint) for a, b, c, paint in triangles]
    if centre:
        # Put the middle of the model's footprint at the origin (the studio's
        # origin is its outline's centroid); the shift is printed.
        if mid is None:
            mid = tuple((max(p[k] for p in points) + min(p[k] for p in points)) // 2 for k in (0, 1))
        print(f"{path}: footprint middle {mid[0] / 100:.2f} m east, {mid[1] / 100:.2f} m north of the GLB's origin")
        points = [(x - mid[0], y - mid[1], z) for x, y, z in points]
    if len(points) > 65535 or len(triangles) > 65535:
        raise SystemExit(f"{path}: too many vertices or triangles")
    out = bytearray(struct.pack("<H", len(points)))
    for x, y, z in points:
        low_z, high_z = (0, 65535) if unsigned_z else (-32768, 32767)
        if not (-32768 <= x <= 32767 and -32768 <= y <= 32767 and low_z <= z <= high_z):
            raise SystemExit(f"{path}: vertex {(x, y, z)} cm out of range")
        out += struct.pack("<hhH" if unsigned_z else "<hhh", x, y, z)
    out += struct.pack("<H", len(triangles))
    for a, b, c, paint in triangles:
        out += struct.pack("<HHHB", a, b, c, paint)
    low = [min(p[k] for p in points) / 100 for k in range(3)]
    high = [max(p[k] for p in points) / 100 for k in range(3)]
    return bytes(out), len(points), len(triangles), low, high


def without_parts_south_of(south, points, norths, triangles):
    """`triangles` without every part that reaches south of `south`
    metres (decision 938: the Tian Tan Buddha's long flight of stairs down
    a hillside the game's ground does not follow). A part is the triangles
    of one material joined through shared vertices."""
    parent = {}

    def find(a):
        parent.setdefault(a, a)
        while parent[a] != a:
            parent[a] = parent[parent[a]]
            a = parent[a]
        return a

    for a, b, c, paint in triangles:
        parent[find((paint, b))] = find((paint, a))
        parent[find((paint, c))] = find((paint, a))
    lowest = {}
    for node in list(parent):
        root = find(node)
        lowest[root] = min(lowest.get(root, math.inf), norths[node[1]])
    return [t for t in triangles if lowest[find((t[3], t[0]))] >= south]


def mesh_file(enum, materials, source, models, tool="tools/landmarks/glb_to_swift.py"):
    """A registered landmark's mesh file (decision 895): `models` is
    (name, encoded bytes, vertices, triangles) for each."""
    lines = [
        f"// Generated by {tool} from " + source + "; do not edit by hand.",
        "// Palette order: " + ", ".join(materials) + ".",
        "",
        f"extension {enum} {{",
        "    /// Each model's encoded mesh, by its GLB's file name (decision 895).",
        "    static let encoded: [String: String] = [",
    ]
    for name, data, v, t in models:
        text = base64.b64encode(data).decode()
        lines.append(f"        // {v} vertices, {t} triangles.")
        lines.append(f'        "{name}": """')
        for i in range(0, len(text), 120):
            lines.append("        " + text[i:i + 120])
        lines.append('        """,')
    lines += ["    ]", "}", ""]
    return "\n".join(lines)


def legacy_file(preset, entries):
    """A shared legacy file: `entries` is (name, encoded bytes, vertices,
    triangles, low, high) for each."""
    lines = preset["header"] + [
        "",
        f"extension {preset['enum']} {{",
        f"    /// Each model, by its file name, as `tools/landmarks/glb_to_swift.py` encodes it.",
        f"    static let {preset['table']}: [String: String] = [",
    ]
    for name, data, v, t, low, high in entries:
        lines.append(f"        // {v} vertices, {t} triangles; {low} to {high} m." if preset["bounds"]
                     else f"        // {v} vertices, {t} triangles.")
        lines.append(f'        "{name}": "{base64.b64encode(data).decode()}",')
    lines += ["    ]", "}", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--out", required=True)
    parser.add_argument("--enum", help="the registered landmark's Swift enum")
    parser.add_argument("--materials", help="material names in palette order, comma-separated")
    parser.add_argument("--source", help="where the GLBs are, for the file's first line")
    parser.add_argument("--centre", action="store_true", help="move the near (first) model's footprint middle to the origin, every model by the same")
    parser.add_argument("--turn", type=float, default=0.0,
                        help="turn the models this many degrees anticlockwise, seen from above, as OpenStreetMap lays them")
    parser.add_argument("--raise", dest="lift", type=float, default=0.0,
                        help="raise the models this many metres, so a part the studio built below its ground (a plinth down a "
                             "hillside) stands at 0; the registration's `sink` lowers it again")
    parser.add_argument("--without-parts-south-of", dest="south", type=float,
                        help="leave out every part (the triangles of one material joined through shared vertices) that reaches "
                             "south of this many metres north of the GLB's origin, before any turn: a flight of stairs down a "
                             "hillside the game's ground does not follow (decision 938)")
    parser.add_argument("--legacy", choices=sorted(LEGACY), help="write a landmark file made before the registry")
    parser.add_argument("--assets", help="--legacy sunmoon: the folder of the Sun Moon Lake GLBs")
    parser.add_argument("--nodes", action="store_true",
                        help="apply each node's translation, rotation and scale (one mesh placed twice, as the Dragon and "
                             "Tiger Pagodas' two towers), rather than refuse a transformed node")
    parser.add_argument("--allow-ground-plate", action="store_true", help="a level plate beyond the body belongs to the model")
    parser.add_argument("glbs", nargs="*")
    a = parser.parse_args()
    if a.legacy:
        preset = LEGACY[a.legacy]
        if a.legacy == "sunmoon":
            if not a.assets:
                raise SystemExit("--legacy sunmoon needs --assets")
            jobs = [(name, os.path.join(a.assets, name + ".glb"), SUN_MOON_SCALES[name.replace("-lod1", "")])
                    for name in SUN_MOON_MODELS]
        else:
            jobs = [(os.path.splitext(os.path.basename(p))[0], p, (1, 1, 1)) for p in sorted(a.glbs)]
        entries = []
        for name, path, scale in jobs:
            data, v, t, low, high = encode(path, preset["materials"], preset["aliases"], preset["axes"], preset["nodes"],
                                           scale, preset["unsigned_z"], a.centre)
            ground_plate.check(data, name, signed_z=not preset["unsigned_z"], allow=a.allow_ground_plate)
            print(f"{name}: {v} vertices, {t} triangles, {len(data)} bytes")
            entries.append((name, data, v, t, low, high))
        open(a.out, "w").write(legacy_file(preset, entries))
        return
    if not (a.enum and a.materials and a.source and a.glbs):
        raise SystemExit("a registered landmark needs --enum, --materials, --source and its GLBs")
    materials = a.materials.split(",")
    models = []
    # Decision 927: every model is moved by the first (near) model's
    # footprint middle, so a far model smaller than the near one (the
    # Dragon and Tiger Pagodas' has no zigzag bridge) stays where it is.
    mid = None
    for path in a.glbs:
        if a.centre and mid is None:
            _, _, _, low, high = encode(path, materials, nodes=a.nodes, turn=a.turn, lift=a.lift, south=a.south)
            mid = tuple((round(high[k] * 100) + round(low[k] * 100)) // 2 for k in (0, 1))
        data, v, t, _, _ = encode(path, materials, nodes=a.nodes, centre=a.centre, turn=a.turn, lift=a.lift, mid=mid, south=a.south)
        name = os.path.splitext(os.path.basename(path))[0]
        ground_plate.check(data, name, allow=a.allow_ground_plate)
        print(f"{name}: {v} vertices, {t} triangles, {len(data)} bytes")
        models.append((name, data, v, t))
    open(a.out, "w").write(mesh_file(a.enum, materials, a.source, models))


if __name__ == "__main__":
    main()
