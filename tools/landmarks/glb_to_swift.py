#!/usr/bin/env python3
"""Write landmark GLBs into the game's Swift source as encoded meshes (no
third-party modules). Decision 895: the one tool for every landmark.

A new landmark (decision 895's registry, the way decision 782 registers a
train) gets a mesh file of its own:

    python3 -I tools/landmarks/glb_to_swift.py \
        --enum Map3DFukuokaDome \
        --materials wallPale,roofFlat,glassSilver \
        --source "railway-assets-private-2, game-art-previews/docs/art/fukuoka-landmarks-2026-11/revision-4" \
        --centre --out Sources/GamePresentation/Map3DFukuokaDomeMesh.swift \
        DIR/fukuoka-dome.glb DIR/fukuoka-dome-far.glb

`--materials` names the GLB's materials in the order of the landmark's
`palette` (its registration holds the colour of each, from
``Map3DPalette``, so the game, not the GLB, decides each colour), as
`tools/train-models/glb_to_swift.py` does for a train.

The landmarks made before the registry keep their shared files until they
are made again (the owner, 2026-11-20: the old ones are not moved for the
sake of it); `--legacy` writes those files as they are:

    --legacy hongkong   Map3DHongKongLandmarkMeshes.swift  (hk-landmarks-2026-11/revision-11/*.glb)
    --legacy sunmoon    Map3DSunMoonLandmarkMeshes.swift   (OpenWorld/reference_snapshot/play/assets/sunmoon)
    --legacy tpe-mrt    Map3DTaipeiMRTStationMeshes.swift  (tpe-mrt-elevated-2026-11/revision-4/*.glb)

The studio builds a landmark in Blender with one material per palette
colour, the footprint's middle at the origin (or `--centre` moves it
there), the ground at y 0, glTF's axes (+x east, +y up, +z south). This
tool

- welds the vertices at 1 cm and turns glTF's axes onto the landmark's own
  (+x east, +y north, +z up) by a rotation, so the winding is kept (the Taipei
  MRT stations keep glTF's axes; Sun Moon Lake's models apply their nodes'
  transforms and the earlier version's scales);
- gives each triangle the index of its material's name in the material
  list;
- writes each GLB, named by its file name, as base64 of: the vertex count
  (UInt16), each vertex x and y in centimetres (Int16) and z in
  centimetres (UInt16, up to 655 m; Int16 for the legacy Sun Moon Lake and
  MRT files), the triangle count (UInt16), each triangle's three vertex
  indices (UInt16) and material index (UInt8), little-endian
  (``Map3DLandmarkRegistration`` reads it);
- stops when a model brings its own ground plate (`ground_plate.py`,
  OLD-PORT-AUDIT), unless `--allow-ground-plate` says it belongs.
"""

