#!/usr/bin/env python3
"""Writes Sources/GamePresentation/RealStationPlatformTypes.swift from
platform_types.json (decision 760): which real stations a purchase lays as
an island (two tracks 11 m apart) and which as two side platforms (two
tracks 5 m apart). The others (one side platform, or OSM draws none) keep
the one track a purchase lays.

    python3 -I tools/station-platform-types/make_swift_table.py \
        tools/station-platform-types/platform_types.json \
        Sources/GamePresentation/RealStationPlatformTypes.swift
"""
import json
import sys

# Decision 741: where the railway's own station plans and OSM disagree,
# the plans win (`docs/decisions/741.md`).
OFFICIAL = {
    ("tra_sched", "頭城"): "island",   # 1 island 1 side
    ("thsr_sched", "板橋"): "island",  # an island on each of two levels
    ("thsr_sched", "台北"): "island",
    ("thsr_sched", "苗栗"): "side",
}


def laid(station):
    official = OFFICIAL.get((station["system"], station["station"]))
    if official:
        return official
    kind = station["type"]
    if kind in ("island", "mixed"):
        return "island"
    if kind == "side" and station["sides"] >= 2:
        return "side"
    return None


def main(source, out):
    stations = json.load(open(source, encoding="utf-8"))["stations"]
    groups = {"island": [], "side": []}
    for station in stations:
        kind = laid(station)
        if kind:
            groups[kind].append(f'{station["system"]}|{station["station"]}')

    def lines(ids):
        ids = sorted(set(ids))
        rows = []
        for start in range(0, len(ids), 8):
            rows.append("        " + ", ".join(f'"{i}"' for i in ids[start:start + 8]) + ",")
        return "\n".join(rows)

    text = f"""// Generated by tools/station-platform-types/make_swift_table.py from
// platform_types.json (© OpenStreetMap contributors, ODbL 1.0) with the
// railway's own station plans where they disagree (decision 741). Do not
// edit by hand: change the tool and run it again (decision 760).

/// How a real station's platforms stand, as a purchase lays it (decision
/// 760): keyed by ``RealRailways/Station/id``.
enum RealStationPlatformTypes {{
    /// Stations whose platform is an island (or an island and a side
    /// platform): two tracks, the island between.
    static let island: Set<String> = [
{lines(groups["island"])}
    ]

    /// Stations with a side platform on each of two tracks.
    static let side: Set<String> = [
{lines(groups["side"])}
    ]
}}
"""
    open(out, "w", encoding="utf-8").write(text)
    print(len(groups["island"]), "island,", len(groups["side"]), "side")


if __name__ == "__main__":
    main(*sys.argv[1:3])
