#!/usr/bin/env python3
"""Decision 882: the platform name boards' letters (`Map3DBoardGlyphs`).

Every character of the game's bundled names (each string in the JSON
files under `RailwayGameApp/Resources`, the base map aside), kana, and
Latin letters, figures and signs, drawn from Noto Sans TC Bold (SIL Open
Font License 1.1, `Licenses/` beside it in the app) on a grid of
`GRID` cells, each glyph kept as the fewest rectangles a greedy merge of
its filled cells gives. The Swift file it writes is generated; run again
when names with new characters are bundled:

    curl -sSL -o /tmp/NotoSansTC-Bold.otf \
      https://cdn.jsdelivr.net/gh/notofonts/noto-cjk@main/Sans/SubsetOTF/TC/NotoSansTC-Bold.otf
    python3 -I tools/platform-name-board/build_glyphs.py /tmp/NotoSansTC-Bold.otf \
      > Sources/GamePresentation/Map3DBoardGlyphs.swift

Needs Pillow. The font file is not committed.
"""
import base64
import json
import os
import sys

from PIL import Image, ImageDraw, ImageFont

GRID = 16
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..')
RESOURCES = os.path.join(ROOT, 'RailwayGameApp', 'Resources')


def bundled_characters():
    chars = set()

    def walk(value):
        if isinstance(value, dict):
            for key, item in value.items():
                chars.update(key)
                walk(item)
        elif isinstance(value, list):
            for item in value:
                walk(item)
        elif isinstance(value, str):
            chars.update(value)

    for folder, dirs, files in os.walk(RESOURCES):
        dirs[:] = sorted(d for d in dirs if d != 'BaseMap')
        for name in sorted(files):
            if name.endswith('.json'):
                with open(os.path.join(folder, name), encoding='utf-8') as handle:
                    walk(json.load(handle))
    wide = {c for c in chars if ord(c) >= 0x2E80 and not 0xE000 <= ord(c) <= 0xF8FF}
    latin = {chr(c) for c in range(0x21, 0x7F)} | {chr(c) for c in range(0xC0, 0x180)} - {'×', '÷'}
    kana = {chr(c) for c in range(0x3041, 0x3097)} | {chr(c) for c in range(0x30A1, 0x30FB)} | {'ー', '・', '〇'}
    return sorted(wide | latin | kana)


def rectangles(cells):
    """The filled cells as rectangles: runs along each row, a run grown
    down while the rows below hold the same run."""
    filled = [row[:] for row in cells]
    found = []
    for y in range(GRID):
        x = 0
        while x < GRID:
            if not filled[y][x]:
                x += 1
                continue
            end = x
            while end + 1 < GRID and filled[y][end + 1]:
                end += 1
            bottom = y
            while bottom + 1 < GRID and all(filled[bottom + 1][x:end + 1]):
                bottom += 1
            for row in range(y, bottom + 1):
                for col in range(x, end + 1):
                    filled[row][col] = False
            found.append((x, y, end - x + 1, bottom - y + 1))
            x = end + 1
    return found


def main():
    font_path = sys.argv[1]
    # The em a little under the grid, so strokes keep a cell's margin.
    scale = 4
    font = ImageFont.truetype(font_path, GRID * scale * 15 // 16)
    ascent, _ = font.getmetrics()
    baseline = GRID * scale * 13 // 16  # from the top
    entries = []
    missing = font.getmask('￿').getbbox()
    for char in bundled_characters():
        mask = font.getmask(char)
        if not mask.getbbox() or char.isspace():
            continue
        advance = font.getlength(char) / scale
        image = Image.new('L', (GRID * scale, GRID * scale), 0)
        width = round(advance * scale)
        x0 = max(0, (GRID * scale - width) // 2) if advance > GRID * 0.75 else 0
        ImageDraw.Draw(image).text((x0, baseline - ascent), char, fill=255, font=font)
        small = image.resize((GRID, GRID), Image.BOX)
        cells = [[small.getpixel((x, y)) >= 110 for x in range(GRID)] for y in range(GRID)]
        rects = rectangles(cells)
        if not rects:
            continue
        cells_wide = GRID if advance > GRID * 0.75 else max(1, min(GRID, round(advance)))
        data = bytes([cells_wide - 1, len(rects)]) + b''.join(
            bytes([(x << 4) | y, ((w - 1) << 4) | (h - 1)]) for x, y, w, h in rects)
        entries.append((char, data))
    rect_total = sum(e[1][1] for e in entries)
    blob = b''.join(c.encode('utf-8') + d for c, d in entries)
    encoded = base64.b64encode(blob).decode('ascii')
    lines = [encoded[i:i + 116] for i in range(0, len(encoded), 116)]
    out = sys.stdout
    out.write('// Generated by tools/platform-name-board/build_glyphs.py (decision 882); do not edit.\n')
    out.write(f'// {len(entries)} glyphs, {rect_total} rectangles, from Noto Sans TC Bold\n')
    out.write('// (SIL Open Font License 1.1) on a 16-cell grid.\n\n')
    out.write('extension Map3DBoardGlyphs {\n')
    out.write('    /// Each glyph: its character in UTF-8, its width in cells less one, its\n')
    out.write('    /// rectangles\' count, then two bytes each (x and y from the top left,\n')
    out.write('    /// width and height less one, four bits each); in Base64.\n')
    out.write('    static let packed = """\n')
    for line in lines:
        out.write(f'        {line}\n')
    out.write('        """\n}\n')
    print(f'{len(entries)} glyphs, {rect_total} rectangles, {len(encoded)} bytes', file=sys.stderr)


if __name__ == '__main__':
    main()
