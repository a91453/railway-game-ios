import Foundation

/// Independently built PP push-pull passenger-car study. This is a static asset,
/// not an operating train or a push-pull-control implementation. Dimensions and
/// photo-derived stations are distinguished in the accompanying source record.
public enum Map3DPPPassenger {
    public enum Role: String, CaseIterable, Sendable {
        case ppm2500, pph1300, ppc1400, ppt1000
    }
    public static let roles = Role.allCases
    /// Display interpretation of the official 20.300m length; its engineering endpoints are not established.
    public static let bodyHalfLength: Float = 9.725
    public static let couplingHalfLength: Float = 10.150
    public static let gangwayHalfLength: Float = 10.140
    public static let couplerHeight: Float = 0.90
    public static let bodyColor = Map3DE500.bodyColor
    public static let glassColor = Map3DE500.glassColor

    public static func model(_ role: Role, far: Bool = false) -> Map3DModelPack.Model {
        var b = StationKitBuilder()
        b.ppBody(role, far: far)
        return .flat(named: "pp-" + role.rawValue + (far ? "-far" : ""), from: b.mesh)
    }

    /// Independent side tables; the second side is not generated by reflecting
    /// the first. Window stations and equipment dimensions remain photo estimates.
    public static func windows(_ role: Role, left: Bool) -> [(centre: Float, width: Float)] {
        switch (role, left) {
        case (.ppm2500, true): return [(2.30, 1.88), (4.65, 1.88), (6.32, 0.58), (8.05, 0.44)]
        case (.ppm2500, false): return [(-6.95, 0.48), (-5.35, 0.66), (-3.45, 1.90), (-0.95, 1.90), (1.55, 1.90), (4.05, 1.90), (6.55, 1.90)]
        case (.pph1300, true): return [(-5.35, 0.58), (-4.15, 0.58), (-2.28, 1.72), (-0.10, 1.72), (2.08, 1.72), (4.26, 1.72), (6.00, 0.58), (7.20, 0.58)]
        case (.pph1300, false): return [(-7.20, 0.58), (-6.00, 0.58), (-4.26, 1.72), (-2.08, 1.72), (0.10, 1.72), (2.28, 1.72), (4.15, 0.58), (5.35, 0.58), (7.70, 0.62)]
        case (.ppc1400, true): return [(-7.52, 0.62), (-5.25, 0.62), (-3.40, 1.65), (-1.25, 1.65), (0.90, 1.65), (3.05, 1.65), (5.20, 1.65), (6.88, 0.58), (8.00, 0.58)]
        case (.ppc1400, false): return [(-7.40, 0.58), (-6.20, 0.58), (-4.45, 1.65), (-2.30, 1.65), (-0.15, 1.65), (2.00, 1.65), (4.15, 1.65), (5.95, 0.58), (7.75, 0.58)]
        case (.ppt1000, true): return [(-7.52, 0.62), (-5.25, 0.62), (-3.40, 1.65), (-1.25, 1.65), (0.90, 1.65), (3.05, 1.65), (5.20, 1.65), (6.88, 0.58), (8.00, 0.58)]
        case (.ppt1000, false): return [(-7.40, 0.58), (-6.20, 0.58), (-4.45, 1.65), (-2.30, 1.65), (-0.15, 1.65), (2.00, 1.65), (4.15, 1.65), (5.95, 0.58), (7.75, 0.58)]
        }
    }
}

extension StationKitBuilder {
    private func ppRoofHeight(_ z: Float) -> Float {
        3.30 + 0.52 * sqrtf(max(0, 1 - (z / 1.4425) * (z / 1.4425)))
    }
    private mutating func ppPrism(_ section: [(Float, Float)], x: Float, length: Float, color: UInt32) {
        let rings: [[Map3DPoint]] = [-1, 1].map { end in section.map { Map3DPoint(x + Float(end) * length / 2, $0.1, $0.0) } }
        let inside = Map3DPoint(x, section.map(\.1).reduce(0, +) / Float(section.count), 0)
        for i in section.indices {
            let j = (i + 1) % section.count
            face([rings[0][i], rings[0][j], rings[1][j], rings[1][i]], inside: inside, color: color)
        }
        for ring in rings { face(ring, inside: inside, color: color) }
    }
    private mutating func ppPanel(_ points: [Map3DPoint], offset: Map3DPoint, color: UInt32) {
        let q = points.map { $0 + offset }, inside = (points + q).reduce(.zero, +) * (1 / Float(points.count * 2))
        face(points, inside: inside, color: color)
        face(q, inside: inside, color: color)
        for i in points.indices {
            let j = (i + 1) % points.count
            face([points[i], points[j], q[j], q[i]], inside: inside, color: color)
        }
    }
    private func ppRounded(_ x: Float, _ y: Float, width: Float, height: Float, radius: Float, far: Bool) -> [(Float, Float)] {
        let n = far ? 2 : 4
        var p: [(Float, Float)] = []
        for (cx, cy, a) in [(x + width / 2 - radius, y + height / 2 - radius, Float(0)),
                            (x - width / 2 + radius, y + height / 2 - radius, Float.pi / 2),
                            (x - width / 2 + radius, y - height / 2 + radius, Float.pi),
                            (x + width / 2 - radius, y - height / 2 + radius, Float.pi * 1.5)] {
            for i in 0...n {
                let t = a + Float(i) * Float.pi / (2 * Float(n))
                p.append((cx + cosf(t) * radius, cy + sinf(t) * radius))
            }
        }
        return p
    }
    private mutating func ppSideWindow(_ x: Float, _ y: Float, side: Float, width: Float, height: Float, far: Bool, opaque: Bool = false) {
        let frame = ppRounded(x, y, width: width + 0.075, height: height + 0.075, radius: 0.14, far: far)
        let pane = ppRounded(x, y, width: width, height: height, radius: 0.12, far: far)
        ppPanel(frame.map { Map3DPoint($0.0, $0.1, side * 1.4435) }, offset: Map3DPoint(0, 0, side * 0.013), color: Self.ink)
        ppPanel(pane.map { Map3DPoint($0.0, $0.1, side * 1.4575) }, offset: Map3DPoint(0, 0, side * 0.012), color: opaque ? Map3DPalette.shopAwnings[3] : Map3DPPPassenger.glassColor)
    }

    fileprivate mutating func ppBody(_ role: Map3DPPPassenger.Role, far: Bool) {
        let white = Map3DPalette.shopAwnings[3], teal = Map3DPPPassenger.bodyColor
        let dark = Self.ink, steel = Self.steel, tire = Map3DStreetModel.tyre
        let half = Map3DPPPassenger.bodyHalfLength
        // Main shape: straight passenger-car walls and an elliptical transverse
        // roof; horizontal colour boundaries are shell strips, never overlay skins.
        var section: [(Float, Float)] = [(-1.4425, 1.15), (1.4425, 1.15)]
        let wallLevels: [Float] = [1.67, 1.715, 1.83, 1.875, 3.20, 3.30]
        for h in wallLevels { section.append((1.4425, h)) }
        let roofSteps = far ? 12 : 20
        for i in 1..<roofSteps {
            let a = Float(i) * Float.pi / Float(roofSteps)
            section.append((1.4425 * cosf(a), 3.30 + 0.52 * sinf(a)))
        }
        section.append((-1.4425, 3.30))
        for h in wallLevels.dropLast().reversed() { section.append((-1.4425, h)) }
        let inside = Map3DPoint(0, 2.4, 0)
        let ends: [[Map3DPoint]] = [-half, half].map { x in section.map { Map3DPoint(x, $0.1, $0.0) } }
        for i in section.indices {
            let j = (i + 1) % section.count, h = (section[i].1 + section[j].1) / 2
            let color: UInt32 = h >= 3.20 ? steel : h >= 1.875 ? teal : (h > 1.67 && h < 1.715) || (h > 1.83 && h < 1.875) ? dark : white
            face([ends[0][i], ends[0][j], ends[1][j], ends[1][i]], inside: inside, color: color)
        }
        for e in ends {
            let c = Map3DPoint(e[0].x, 2.4, 0)
            for i in e.indices { face([c, e[i], e[(i + 1) % e.count]], inside: inside, color: white) }
        }
        box(0, 1.015, 0, 2 * half - 0.15, 2.65, 0.135, dark)
        // Two separate low-profile air conditioners. Their curved lower cross
        // section follows the real model roof; casing, grille and divisions differ.
        for x: Float in [-7.85, 7.85] {
            let zs: [Float] = [-1.02, -0.91, -0.68, -0.34, 0, 0.34, 0.68, 0.91, 1.02]
            let lower = zs.map { ppRoofHeight($0) }
            let upper = zs.map { abs($0) > 0.92 ? Float(3.94) : Float(4.025) }
            for i in 0..<zs.count - 1 {
                let a = zs[i], b = zs[i + 1]
                let centre = Map3DPoint(x, (lower[i] + lower[i + 1] + upper[i] + upper[i + 1]) / 4, (a + b) / 2)
                let rings = [x - 1.065, x + 1.065].map { X in
                    [Map3DPoint(X, lower[i], a), Map3DPoint(X, lower[i + 1], b),
                     Map3DPoint(X, upper[i + 1], b), Map3DPoint(X, upper[i], a)]
                }
                for ring in rings { face(ring, inside: centre, color: steel) }
                for edge in [0, 2] {
                    face([rings[0][edge], rings[0][edge + 1], rings[1][edge + 1], rings[1][edge]], inside: centre, color: steel)
                }
                if i == 0 { face([rings[0][0], rings[0][3], rings[1][3], rings[1][0]], inside: centre, color: steel) }
                if i == zs.count - 2 { face([rings[0][1], rings[0][2], rings[1][2], rings[1][1]], inside: centre, color: steel) }
            }
            box(x + 0.40, 4.025, 0, 0.76, 1.60, 0.007, dark)
            if far { box(x, 4.033, 0, 0.025, 1.64, 0.010, steel) }
            if !far {
                for dx: Float in [-0.65, -0.28, 0.09, 0.46, 0.83] {
                    box(x + dx, 4.033, 0, 0.025, 1.64, 0.010, steel)
                }
                for side: Float in [-1, 1] {
                    for i in 0..<7 { box(x - 0.82 + Float(i) * 0.25, 3.92, side * 1.026, 0.055, 0.012, 0.035, dark) }
                }
            }
        }
        if !far {
            for z: Float in [-1.20, -0.95, -0.70, -0.45, -0.20, 0.20, 0.45, 0.70, 0.95, 1.20] {
                box(0, ppRoofHeight(z), z, 13.38, 0.018, 0.014, steel)
            }
        }
        for side: Float in [-1, 1] {
            for (x, width) in Map3DPPPassenger.windows(role, left: side < 0) {
                let opaque = (role == .ppt1000 && side < 0 && x < -7.4) || (role == .pph1300 && side > 0 && x > 7.6)
                let height: Float = role == .ppm2500 && side < 0 && x > 7.8 ? 0.54 : width < 0.8 ? 0.84 : 0.93
                let y: Float = role == .ppm2500 && side < 0 ? (x > 7.8 ? 2.79 : width < 0.8 ? 2.66 : 2.56) : 2.59
                ppSideWindow(x, y, side: side, width: width, height: height, far: far, opaque: opaque)
                if !far && width < 0.8 && !opaque && role != .ppm2500 {
                    box(x, 2.74, side * 1.471, width - 0.04, 0.014, 0.025, steel)
                }
            }
            for end: Float in [-1, 1] {
                let x = end * 9.13
                if far { box(x, 0.85, side * 1.4925, 0.65, 0.22, 0.07, steel) }
                // Thin door leaf seated on the planar side wall; no box-sized jamb.
                box(x, 1.21, side * 1.4475, 0.72, 0.010, 1.94, dark)
                box(x, 1.235, side * 1.4555, 0.67, 0.010, 1.89, teal)
                ppSideWindow(x, 2.65, side: side, width: 0.30, height: 0.91, far: far)
                if !far {
                    box(x - end * 0.23, 2.04, side * 1.4755, 0.12, 0.025, 0.035, white)
                    let hand = x - end * 0.52
                    beam(Map3DPoint(hand, 1.58, side * 1.4925), Map3DPoint(hand, 2.27, side * 1.4925), 0.026, steel)
                    for h: Float in [1.58, 2.27] { box(hand, h, side * 1.4575, 0.065, 0.05, 0.035, steel) }
                    box(x, 1.03, side * 1.4825, 0.72, 0.20, 0.08, steel)
                    box(x, 0.85, side * 1.4925, 0.65, 0.22, 0.07, steel)
                    for h: Float in [0.85, 1.03] {
                        beam(Map3DPoint(x - 0.28, h, side * 1.4925), Map3DPoint(x - 0.28, 1.15, side * 1.43), 0.035, steel)
                        beam(Map3DPoint(x + 0.28, h, side * 1.4925), Map3DPoint(x + 0.28, 1.15, side * 1.43), 0.035, steel)
                    }
                }
            }
            // Nonverbal destination panels; no real route, number or trademark.
            box(5.90, 3.04, side * 1.4455, 0.48, 0.018, 0.16, dark)
            if !far { box(5.90, 3.075, side * 1.474, 0.29, 0.008, 0.065, teal) }
        }
        // End vestibules, compressed bellows and the same coupler height used by
        // the accepted E500. Bellows may be removed only at locomotive interface.
        for end: Float in [-1, 1] {
            box(end * (half + 0.035), 1.19, 0, 0.07, 1.10, 2.05, dark)
            box(end * (half + 0.078), 1.25, 0, 0.020, 0.81, 1.91, steel)
            box(end * (half + 0.098), 2.50, 0, 0.018, 0.46, 0.54, Map3DPPPassenger.glassColor)
            let folds = far ? 2 : 5
            let reach = Map3DPPPassenger.gangwayHalfLength - half
            for i in 0..<folds {
                let x = end * (half + reach * (Float(i) + 0.5) / Float(folds))
                let thickness = reach / Float(folds) * 0.78
                for z: Float in [-0.58, 0.58] { box(x, 1.20, z, thickness, 0.11, 2.14, dark) }
                box(x, 3.23, 0, thickness, 1.27, 0.11, dark)
                box(x, 1.20, 0, thickness, 1.27, 0.10, dark)
            }
            box(end * (half + reach / 2), 1.16, 0, reach, 1.05, 0.04, steel)
            box(end * (half + 0.20), 0.77, 0, 0.40, 0.33, 0.24, dark)
            let tip = Map3DPPPassenger.couplingHalfLength
            box(end * (tip - 0.055), 0.78, 0, 0.11, 0.44, 0.24, steel)
            if !far { for z: Float in [-0.75, 0.75] {
                beam(Map3DPoint(end * (half + 0.045), 1.25, z), Map3DPoint(end * (half + 0.22), 0.58, z), 0.044, dark)
                beam(Map3DPoint(end * (half + 0.22), 0.58, z), Map3DPoint(end * (half + 0.13), 0.48, z * 0.8), 0.044, dark)
            }}
        }
        // Two conventional two-axle bogies. Suspension detail is a visual
        // simplification, not a claim about hidden piping or exact mechanisms.
        // Source label 軸距=14.300m interpreted as bogie-centre distance; not internal wheelbase.
        for centre: Float in [-7.15, 7.15] {
            box(centre, 0.61, 0, 3.45, 0.80, 0.25, steel)
            box(centre, 0.86, 0, 1.40, 1.90, 0.155, dark)
            for dx: Float in [-1.25, 1.25] {
                let x = centre + dx
                civicTube(Map3DPoint(x, 0.43, -0.72), Map3DPoint(x, 0.43, 0.72), radius: 0.065, color: steel, sides: 6)
                for side: Float in [-1, 1] {
                    civicTube(Map3DPoint(x, 0.43, side * 0.50), Map3DPoint(x, 0.43, side * 0.67), radius: 0.43, color: tire, sides: far ? 8 : 12)
                    civicTube(Map3DPoint(x, 0.43, side * 0.67), Map3DPoint(x, 0.43, side * 0.71), radius: 0.28, color: steel, sides: far ? 8 : 12)
                    civicTube(Map3DPoint(x, 0.43, side * 0.71), Map3DPoint(x, 0.43, side * 1.04), radius: 0.095, color: steel, sides: far ? 4 : 8)
                    box(x, 0.32, side * 1.04, 0.42, 0.22, 0.24, dark)
                }
            }
            for side: Float in [-1, 1] {
                box(centre, 0.74, side * 1.04, 3.38, 0.18, 0.15, steel)
                box(centre, 0.55, side * 1.04, 3.38, 0.19, 0.20, steel)
                for dx: Float in [-0.67, 0.67] {
                    cylinder(centre + dx, 0.69, side * 1.04, radius: 0.13, height: 0.27, color: dark, sides: far ? 4 : 8)
                    box(centre + dx, 0.96, side * 1.04, 0.48, 0.32, 0.055, steel)
                    if !far { for h: Float in [0.72, 0.80, 0.88] { cylinder(centre + dx, h, side * 1.04, radius: 0.16, height: 0.025, color: steel, sides: 8) } }
                }
            }
        }
        let multifunction = role == .ppm2500
        // Asymmetric visible underfloor masses. Their exact hidden connections
        // are deliberately omitted, rather than mirrored as invented machinery.
        for (x, length, side) in [(Float(-3.5), multifunction ? Float(2.5) : Float(1.8), Float(-0.63)),
                                  (Float(-0.8), Float(1.7), Float(-0.63)),
                                  (Float(2.0), multifunction ? Float(1.8) : Float(1.2), Float(0.63)),
                                  (Float(3.8), Float(0.8), Float(0.63))] {
            box(x, 0.48, side, length, 0.92, 0.53, steel)
            if !far { for d: Float in [-0.33, 0.33] { box(x + d * length, 0.71, side < 0 ? -1.096 : 1.096, 0.025, 0.015, 0.23, dark) } }
        }
        for (x, side, r) in [(Float(2.45), Float(-0.72), Float(0.23)), (Float(-3.0), Float(0.72), Float(0.28))] {
            civicTube(Map3DPoint(x - 0.95, 0.71, side), Map3DPoint(x + 0.95, 0.71, side), radius: r, color: steel, sides: far ? 8 : 12)
            for dx: Float in [-0.65, 0.65] { box(x + dx, 0.90, side, 0.10, 0.38, 0.12, dark) }
        }
    }
}
